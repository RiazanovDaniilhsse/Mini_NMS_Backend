CREATE TABLE alarms
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    device_id          BIGINT                                  NOT NULL,
    rule_id            BIGINT,
    metric_type_id     BIGINT,
    severity           VARCHAR(255),
    status             VARCHAR(255),
    message            VARCHAR(255),
    threshold_snapshot VARCHAR(255),
    triggered_at       TIMESTAMP WITHOUT TIME ZONE,
    acked_at           TIMESTAMP WITHOUT TIME ZONE,
    resolved_at        TIMESTAMP WITHOUT TIME ZONE,
    closed_at          TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_alarms PRIMARY KEY (id)
);

CREATE TABLE device_type_metric_type
(
    device_type_id BIGINT NOT NULL,
    metric_type_id BIGINT NOT NULL
);

CREATE TABLE device_types
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code        VARCHAR(255)                            NOT NULL,
    name        VARCHAR(255),
    description VARCHAR(255),
    CONSTRAINT pk_device_types PRIMARY KEY (id)
);

CREATE TABLE devices
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name           VARCHAR(255),
    ip_address     VARCHAR(255),
    site_id        BIGINT,
    device_type_id BIGINT                                  NOT NULL,
    CONSTRAINT pk_devices PRIMARY KEY (id)
);

CREATE TABLE metric_types
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code       VARCHAR(255)                            NOT NULL,
    name       VARCHAR(255),
    unit       VARCHAR(255),
    value_type VARCHAR(255),
    CONSTRAINT pk_metric_types PRIMARY KEY (id)
);

CREATE TABLE metric_values
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    device_id      BIGINT                                  NOT NULL,
    metric_type_id BIGINT                                  NOT NULL,
    value_num      DECIMAL,
    value_bool     BOOLEAN,
    timestamp      TIMESTAMP WITHOUT TIME ZONE,
    poll_status    VARCHAR(255),
    CONSTRAINT pk_metric_values PRIMARY KEY (id)
);

CREATE TABLE site
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name      VARCHAR(255),
    address   VARCHAR(255),
    latitude  DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    CONSTRAINT pk_site PRIMARY KEY (id)
);

CREATE TABLE threshold_rules
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    device_type_id  BIGINT                                  NOT NULL,
    metric_type_id  BIGINT                                  NOT NULL,
    device_id       BIGINT,
    comparator      VARCHAR(255),
    threshold_value DECIMAL,
    duration_sec    INTEGER,
    severity        VARCHAR(255),
    enabled         BOOLEAN,
    CONSTRAINT pk_threshold_rules PRIMARY KEY (id)
);

